"""Настройки приложения. Всё, что можно подкрутить, собрано здесь."""
import os

# --- LLM (Pollinations) ---
# Бесплатный классический API доступен без ключа: модель openai-fast,
# лимит 1 запрос в 30 секунд (обёртка соблюдает его сама).
# Если установить переменную окружения POLLINATIONS_API_KEY, приложение
# переключится на gen.pollinations.ai — быстрее и больше моделей.
MODEL = os.environ.get("POLLINATIONS_MODEL", "openai-fast")
LLM_TIMEOUT = 180          # сек, только на генерацию (модель может думать долго)
LLM_MAX_TOKENS = 4000      # без этого ответ модели обрывается посреди JSON;
                           # у reasoning-моделей лимит делится с «размышлениями»
LLM_RETRIES = 1            # ретраев при сбое/битом JSON

# --- Поиск книг ---
SEARCH_TIMEOUT = 20        # сек на один HTTP-запрос к book-API
CANDIDATES_LIMIT = 30      # сколько кандидатов собираем максимум
KEYWORDS_PER_QUERY = 4     # сколько поисковых запросов делаем по признакам вкуса

# --- Подборка ---
# На бесплатном режиме ответ модели обрезается на ~1500 токенов, поэтому
# подборка компактная: ровно MAX_PICKS книг, короткие обоснования.
MIN_PICKS = 3              # минимум книг: бесплатная модель любит отдавать меньше пяти
MAX_PICKS = 5              # сколько книг отбираем

# --- Хранилище ---
DB_PATH = "books.db"       # SQLite-файл рядом с app.py
HISTORY_LIMIT = 20         # сколько последних запросов показываем на главной